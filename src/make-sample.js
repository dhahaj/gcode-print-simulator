'use strict';
/* Generates a realistic MK3S test print (twisted fluted vase with infill) in PrusaSlicer's G-code dialect. */
const fs = require('fs');

const out = [];
const w = (s) => out.push(s);
const NOZZLE = 0.4, LH = 0.2, FIL = 1.75, EW = 0.45;
const AREA = Math.PI * FIL * FIL / 4;
const HEIGHT = 44, LAYERS = Math.round(HEIGHT / LH);
const CX = 125, CY = 105;
const f3 = (n) => n.toFixed(3), f5 = (n) => n.toFixed(5);

let x = 0, y = 0;
function eFor(len, width, h) { return (((width - h) * h + Math.PI * h * h / 4) * len) / AREA; }
function travel(nx, ny, feed = 10800) { w(`G1 X${f3(nx)} Y${f3(ny)} F${feed}`); x = nx; y = ny; }
function extrude(nx, ny, width, h) {
  const len = Math.hypot(nx - x, ny - y);
  if (len < 0.01) return;
  w(`G1 X${f3(nx)} Y${f3(ny)} E${f5(eFor(len, width, h))}`);
  x = nx; y = ny;
}
function retract() { w('G1 E-0.8 F2100'); }
function unretract() { w('G1 E0.8 F2100'); }

function radius(theta, z) {
  const t = z / HEIGHT;
  const base = 27 + 7 * Math.sin(t * Math.PI) - 3 * t;
  return base + 2.6 * Math.cos(7 * (theta + t * 1.5));
}
function outline(z, inset) {
  const pts = [], n = 180;
  for (let i = 0; i < n; i++) {
    const a = (i / n) * Math.PI * 2;
    const r = radius(a, z) - inset;
    pts.push([CX + r * Math.cos(a), CY + r * Math.sin(a)]);
  }
  return pts;
}
function loop(pts, width, h, speed) {
  retract();
  travel(pts[0][0], pts[0][1]);
  unretract();
  w(`G1 F${speed}`);
  for (let i = 1; i <= pts.length; i++) { const p = pts[i % pts.length]; extrude(p[0], p[1], width, h); }
}
function scanlines(poly, spacing, angle) {
  const c = Math.cos(angle), s = Math.sin(angle);
  const rot = poly.map(([px, py]) => [(px - CX) * c + (py - CY) * s, -(px - CX) * s + (py - CY) * c]);
  const ys = rot.map((p) => p[1]);
  const lo = Math.min(...ys), hi = Math.max(...ys), lines = [];
  for (let v = lo + spacing / 2; v < hi; v += spacing) {
    const hits = [];
    for (let i = 0; i < rot.length; i++) {
      const a = rot[i], b = rot[(i + 1) % rot.length];
      if ((a[1] <= v) !== (b[1] <= v)) hits.push(a[0] + ((v - a[1]) / (b[1] - a[1])) * (b[0] - a[0]));
    }
    hits.sort((p, q) => p - q);
    for (let k = 0; k + 1 < hits.length; k += 2) lines.push([hits[k], hits[k + 1], v]);
  }
  const toWorld = (u, v) => [CX + u * c - v * s, CY + u * s + v * c];
  return lines.map(([u0, u1, v], i) => (i % 2 === 0 ? [toWorld(u0, v), toWorld(u1, v)] : [toWorld(u1, v), toWorld(u0, v)]));
}

w('; generated by make-sample.js (PrusaSlicer-style G-code for testing)');
w('M73 P0 R60');
w('M201 X1000 Y1000 Z200 E5000 ; sets maximum accelerations, mm/sec^2');
w('M203 X200 Y200 Z12 E120 ; sets maximum feedrates, mm / sec');
w('M204 P1250 R1250 T1250 ; sets acceleration (P, T) and retract acceleration (R), mm/sec^2');
w('M205 X8.00 Y8.00 Z0.40 E4.50 ; sets the jerk limits, mm/sec');
w('M107');
w('M862.3 P "MK3S" ; printer model check');
w('G90 ; use absolute coordinates');
w('M83 ; extruder relative mode');
w('M104 S215 ; set extruder temp');
w('M140 S60 ; set bed temp');
w('M190 S60 ; wait for bed temp');
w('M109 S215 ; wait for extruder temp');
w('G28 W ; home all without mesh bed level');
w('G80 ; mesh bed leveling');
w('G1 Z0.2 F720');
w('G1 Y-3 F1000 ; go outside print area');
w('G92 E0');
w('G1 X60 E9 F1000 ; intro line');
w('G1 X100 E12.5 F1000 ; intro line');
w('G92 E0');
x = 100; y = -3;

for (let l = 0; l < LAYERS; l++) {
  const z = (l + 1) * LH;
  const first = l === 0;
  const solid = l < 4 || l >= LAYERS - 5;
  w(';LAYER_CHANGE');
  w(`;Z:${z.toFixed(3)}`);
  w(`;HEIGHT:${LH}`);
  retract();
  w(`G1 Z${(z + 0.4).toFixed(3)} F10800`);

  if (first) {
    w(';TYPE:Skirt/Brim');
    w(`;WIDTH:${EW}`);
    for (let s = 2; s >= 0; s--) { w(`G1 Z${z.toFixed(3)} F10800`); loop(outline(z, -6 - s * EW), EW, LH, 1200); }
  } else {
    const p = outline(z, 0)[0];
    travel(p[0], p[1]);
    w(`G1 Z${z.toFixed(3)} F10800`);
  }

  const speed = first ? 1200 : 2400;
  w(';TYPE:Perimeter');
  w(`;WIDTH:${EW}`);
  loop(outline(z, EW * 1.5), EW, LH, speed);
  loop(outline(z, EW * 0.5 + EW * 0), EW, LH, speed);
  w(';TYPE:External perimeter');
  loop(outline(z, EW * 0.5), EW, LH, first ? 1200 : 1800);

  const inner = outline(z, EW * 2.4);
  const angle = (l % 2 ? 1 : -1) * Math.PI / 4;
  const lines = scanlines(inner, solid ? EW : 3.2, solid ? angle : (l % 2 ? Math.PI / 2 : 0));
  w(solid ? ';TYPE:Solid infill' : ';TYPE:Internal infill');
  w(`;WIDTH:${EW}`);
  for (const [a, b] of lines) {
    const gap = Math.hypot(a[0] - x, a[1] - y);
    if (gap > 2) { retract(); travel(a[0], a[1]); unretract(); }
    else { w(`G1 X${f3(a[0])} Y${f3(a[1])} F7200`); x = a[0]; y = a[1]; }
    w(`G1 F${first ? 1500 : 3600}`);
    extrude(b[0], b[1], EW, LH);
  }
}

w('G1 E-1 F2100');
w(`G1 Z${(HEIGHT + 10).toFixed(2)} F720 ; Move print head up`);
w('G1 X0 Y200 F3600 ; park');
w('M104 S0');
w('M140 S0');
w('M107');
w('M84');
w('; filament used [mm] = 0');
w('; filament used [g] = 0');
w('; estimated printing time (normal mode) = 0m');
w('; bed_shape = 0x0,250x0,250x210,0x210');
w('; filament_colour = #FA6831');
w('; filament_diameter = 1.75');
w('; filament_type = PLA');
w('; first_layer_height = 0.2');
w('; layer_height = 0.2');
w('; max_print_height = 210');
w('; nozzle_diameter = 0.4');
w('; printer_model = MK3S');

fs.writeFileSync(process.argv[2], out.join('\n') + '\n');
console.log('wrote', process.argv[2], out.length, 'lines');
